async function fillSpeaker(dialog:Locator,name:string,email:string){
  await dialog.getByLabel('Nome Completo').fill(name);
  await dialog.getByLabel('Titulação/Cargo Acadêmico').selectOption('Doutorado');
  await dialog.getByLabel('Instituição de Origem/Afiliação').fill('Instituto Sintético QA');
  await dialog.getByLabel('E-mail Institucional ou de Contato').fill(email);
  await dialog.getByLabel('Mini-biografia/Apresentação').fill('Pesquisa e docência em sistemas distribuídos, com foco em integração e concorrência.');
}

async function checkImages(dialog:Locator){
  await expect.poll(()=>dialog.locator('img').evaluateAll(images=>images.every(image=>image.complete&&image.naturalWidth>0))).toBe(true);
  const images=await dialog.locator('img').evaluateAll(items=>items.map(image=>({src:image.getAttribute('src'),width:image.getBoundingClientRect().width,height:image.getBoundingClientRect().height,natural:image.naturalWidth/image.naturalHeight})).filter(image=>image.width>0&&image.height>0));
  expect(images.length).toBeGreaterThan(0);
  expect(images.filter(image=>Math.abs(image.width/image.height-image.natural)>=0.2)).toEqual([]);
  const iconInputPadding=await dialog.locator('.organizer-dialog__input-icon > input').evaluateAll(inputs=>inputs.map(input=>parseFloat(getComputedStyle(input).paddingLeft)));
  expect(iconInputPadding.filter(padding=>padding<41)).toEqual([]);
  const capacityPadding=await dialog.locator('.activity-capacity > input').evaluateAll(inputs=>inputs.map(input=>parseFloat(getComputedStyle(input).paddingRight)));
  expect(capacityPadding.filter(padding=>padding<70)).toEqual([]);
}

