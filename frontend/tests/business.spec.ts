import {test,expect} from '@playwright/test';
import {randomUUID} from 'node:crypto';

test('Figma: organizer creates and publishes; participant enrolls and pays',async({page,request},info)=>{
  test.setTimeout(120000);
  await expect.poll(async()=>(await request.get('/api/status')).status(),{timeout:60000,message:'Aguardar dependências prontas antes de cadastrar as contas de teste'}).toBe(200);
  const suffix=randomUUID().slice(0,8),owner='qa-ui-owner-'+suffix+'@example.test',participant='qa-ui-participant-'+suffix+'@example.test',password='Teste123',title='Congresso QA '+suffix;
  for(const email of [owner,participant])expect((await request.post('/api/auth/register',{data:{name:email===owner?'Responsável QA':'Participante QA',email,password}})).status()).toBe(201);
  const login=await request.post('/api/auth/login',{data:{email:owner,password}}),{accessToken}=await login.json();
  expect((await request.post('/api/organizations',{headers:{authorization:'Bearer '+accessToken},data:{name:'Instituto QA '+suffix}})).status()).toBe(201);
  await page.goto('/organizacao/login');
  await page.getByLabel('E-mail',{exact:true}).fill(owner);await page.getByLabel('Senha',{exact:true}).fill(password);await page.getByRole('button',{name:'Entrar',exact:true}).click();
  await page.locator('.topnav').getByRole('link',{name:'Gerenciar Eventos'}).click();
  await page.getByRole('link',{name:'Cadastrar Novo Evento'}).click();
  await page.getByLabel('Nome do Evento/Curso',{exact:true}).fill(title);
  await page.getByLabel('Descrição Geral',{exact:true}).fill('Congresso acadêmico de validação: dados sintéticos, serviços integrados e programação real.');
  await page.getByLabel('Carga Horária',{exact:true}).fill('8');
  await page.getByLabel('Destacar no catálogo',{exact:false}).check();
  await page.getByLabel('Campus, Sala ou Auditório',{exact:true}).fill('UECE · Campus Itaperi');
  const future=new Date(Date.now()+7*86400000).toISOString().slice(0,10);
  await page.getByLabel('Data e hora de início',{exact:true}).fill(future+'T08:00');
  await page.getByLabel('Data e hora de término',{exact:true}).fill(future+'T18:00');
  await page.getByLabel('Horário Padrão das Sessões',{exact:true}).fill('08:00 às 18:00 (BRT)');
  await page.getByRole('button',{name:'Adicionar Palestrante',exact:true}).click();
  const speaker=page.getByRole('dialog',{name:'Cadastrar Professor/Palestrante',exact:true});
  await speaker.getByLabel('Nome Completo').fill('Docente QA');
  await speaker.getByLabel('Titulação/Cargo Acadêmico').selectOption('Doutorado');
  await speaker.getByLabel('Instituição de Origem/Afiliação').fill('UECE');
  await speaker.getByLabel('E-mail Institucional ou de Contato').fill('docente-ui-'+suffix+'@example.test');
  await speaker.getByRole('button',{name:'Salvar',exact:true}).click();
  await page.getByRole('button',{name:'Adicionar Minicurso/Oficina',exact:true}).click();
  const activity=page.getByRole('dialog',{name:'Nova Atividade do Evento',exact:true});
  await activity.getByLabel('Nome da atividade').fill('Workshop de Microsserviços');
  await activity.getByLabel('Descrição e Requisitos').fill('Workshop prático de comunicação entre microsserviços com APIs e mensageria.');
  await activity.getByRole('combobox',{name:/Responsável\/Palestrante/}).fill('Docente QA');
  await activity.getByRole('option',{name:/Docente QA/}).click();
  await activity.getByLabel('Data da Atividade').fill(future);
  await activity.getByLabel('Horário de Início').fill('09:00');
  await activity.getByLabel('Horário de Término').fill('12:00');
  await activity.getByLabel('Local da atividade').fill('Sala 2 · NCAA');
  await activity.getByLabel('Número de vagas').fill('30');
  await activity.getByRole('radio',{name:'Não',exact:true}).check();
  await activity.getByLabel('Valor da inscrição').fill('50');
  await activity.getByRole('button',{name:'Salvar',exact:true}).click();
  await page.screenshot({path:info.outputPath('create-event.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  await page.screenshot({path:info.outputPath('mobile-create-event.png'),fullPage:true});
  await page.setViewportSize({width:1440,height:1024});
  await page.getByRole('button',{name:'Salvar rascunho',exact:true}).click();
  await expect(page).toHaveURL(/\/organizacao\/eventos\/[a-f0-9-]+$/);
  await page.getByRole('button',{name:'Publicar Evento',exact:true}).click();
  await expect(page.getByRole('status')).toHaveText('Evento publicado no catálogo.');
  await page.locator('.topnav').getByRole('link',{name:'Gerenciar Eventos'}).click();
  await expect(page.getByRole('heading',{name:title,exact:true})).toBeVisible();
  await page.screenshot({path:info.outputPath('manage-events.png'),fullPage:true});
  await page.getByRole('button',{name:'Menu da conta'}).click();await page.locator('.account-popover').getByRole('button',{name:'Sair',exact:true}).click();await page.getByRole('button',{name:'Sim, sair',exact:true}).click();
  await page.getByRole('link',{name:'Acesso de participante',exact:true}).click();
  await page.getByLabel('E-mail',{exact:true}).fill(participant);await page.getByLabel('Senha',{exact:true}).fill(password);await page.getByRole('button',{name:'Entrar',exact:true}).click();
  await expect(page).toHaveURL(/\/eventos$/);
  await expect(page.getByRole('heading',{name:title,exact:true}).first()).toBeVisible();
  await page.evaluate(()=>document.fonts.ready);
  await expect(page.getByText('Valores',{exact:true})).toBeVisible();
  await page.screenshot({path:info.outputPath('catalog.png'),fullPage:true});
  const searchPadding=await page.getByLabel('Buscar eventos').evaluate(element=>parseFloat(getComputedStyle(element).paddingLeft));
  expect(searchPadding).toBeGreaterThanOrEqual(40);
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  await page.screenshot({path:info.outputPath('mobile-catalog.png'),fullPage:true});
  await page.setViewportSize({width:1440,height:1024});
  await page.getByLabel('Buscar eventos',{exact:true}).fill(title);
  await page.locator('.event-card').getByRole('link',{name:'Detalhes do Evento',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Sobre o evento',exact:true})).toBeVisible();
  await page.screenshot({path:info.outputPath('event-details.png'),fullPage:true});
  await page.getByRole('link',{name:'Inscrever-se na atividade',exact:true}).click();
  await expect(page.getByRole('dialog',{name:'Inscrição na Atividade',exact:true})).toBeVisible();
  await expect(page.getByRole('dialog',{name:'Inscrição na Atividade',exact:true}).getByRole('heading',{name:title,exact:true})).toBeVisible();
  await page.getByRole('radio',{name:'Workshop de Microsserviços',exact:true}).check();
  await page.screenshot({path:info.outputPath('reservation.png'),fullPage:true});
  await page.getByRole('button',{name:'Continuar',exact:true}).click();
  await expect(page.getByLabel('Nome Completo',{exact:true})).toHaveValue('Participante QA');
  await page.screenshot({path:info.outputPath('participant-data.png'),fullPage:true});
  await page.getByRole('button',{name:'Confirmar e Continuar',exact:true}).click();
  await expect(page).toHaveURL(/\/pagamento\/[a-f0-9-]+$/);
  await expect(page.getByText('Aguardando pagamento',{exact:true})).toBeVisible();
  await page.screenshot({path:info.outputPath('payment.png'),fullPage:true});
  await page.getByRole('button',{name:'Simular pagamento',exact:true}).click();
  await expect(page.getByText('Confirmada',{exact:true})).toBeVisible();
  await page.screenshot({path:info.outputPath('confirmation.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  await expect(page.locator('.checkout-dialog')).toBeVisible();
  const images=await page.locator('.checkout-dialog img').evaluateAll(items=>items.map(image=>({src:image.getAttribute('src'),loaded:image.complete&&image.naturalWidth>0,width:image.getBoundingClientRect().width,height:image.getBoundingClientRect().height,natural:image.naturalWidth/image.naturalHeight})).filter(image=>image.width>0&&image.height>0));
  expect(images.length).toBeGreaterThan(0);
  expect(images.filter(image=>!image.loaded||Math.abs(image.width/image.height-image.natural)>=0.2)).toEqual([]);
  await page.screenshot({path:info.outputPath('mobile-checkout.png'),fullPage:true});
  await page.keyboard.press('Escape');
  await expect(page).toHaveURL(/\/minhas-inscricoes$/);
  await expect(page.locator('.my-registration-activity')).toContainText('Workshop de Microsserviços');
  await page.screenshot({path:info.outputPath('my-registrations.png'),fullPage:true});
});

test('Figma: password recovery form uses generic simulated-delivery response',async({page},info)=>{
  await page.goto('/participante/login');await page.getByRole('link',{name:'Esqueci minha senha'}).click();
  await expect(page.getByRole('heading',{name:'Recuperar sua senha'})).toBeVisible();
  await page.evaluate(()=>document.fonts.ready);
  await page.screenshot({path:info.outputPath('recovery.png'),fullPage:true});
  await page.getByLabel('E-mail cadastrado',{exact:true}).fill('qa-recovery-ui@example.test');
  await page.getByRole('button',{name:'Enviar link de recuperação'}).click();
  await expect(page.getByRole('status')).toContainText('Se o e-mail estiver cadastrado');
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  await page.screenshot({path:info.outputPath('mobile-recovery.png'),fullPage:true});
  await page.goto('/redefinir-senha#token=invalid-test-token');
  await expect(page.getByRole('heading',{name:'Redefinir sua senha',exact:true})).toBeVisible();
  await page.screenshot({path:info.outputPath('reset-password.png'),fullPage:true});
});
